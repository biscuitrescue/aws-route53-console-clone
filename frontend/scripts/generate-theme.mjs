// Writes app/theme.generated.css: the Cloudscape overrides that turn the stock theme into
// the AWS console's. Runs before `dev` and `build`, so the styles are part of the first
// paint instead of being applied by JavaScript after it.
import { writeFileSync } from "node:fs";
import { registerHooks } from "node:module";

// Cloudscape ships ES modules written for bundlers: their relative imports have no file
// extension. Teach Node to resolve those so the theme generator can run in a plain script.
registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if (specifier.startsWith(".")) {
        for (const suffix of [".js", "/index.js"]) {
          try {
            return nextResolve(specifier + suffix, context);
          } catch {
            // try the next candidate
          }
        }
      }
      throw error;
    }
  },
});

const { generateThemeStylesheet } = await import("@cloudscape-design/components/theming");

const ORANGE = "#ff9900";
const ORANGE_PRESSED = "#fa6f00";
const INK = "#0f141a";

// The console sets its text in Amazon Ember, which is not licensed for reuse. It is named
// first so a machine that has it uses it; otherwise Ubuntu Sans stands in, the freely
// licensed face whose glyph widths are closest (within 1% for regular text).
const FONT = '"Amazon Ember", "Ubuntu Sans Variable", "Helvetica Neue", Roboto, Arial, sans-serif';

// The console is stock Cloudscape with two visible differences: its typeface, and primary
// buttons that are orange with dark text in light and dark mode. Values come from the
// console's CSS variables.
const theme = {
  tokens: {
    fontFamilyBase: FONT,
    fontFamilyHeading: FONT,
    fontFamilyDisplay: FONT,
    colorBackgroundButtonPrimaryDefault: ORANGE,
    colorBackgroundButtonPrimaryHover: ORANGE_PRESSED,
    colorBackgroundButtonPrimaryActive: ORANGE_PRESSED,
    colorBorderButtonPrimaryDefault: ORANGE,
    colorBorderButtonPrimaryHover: ORANGE_PRESSED,
    colorBorderButtonPrimaryActive: ORANGE_PRESSED,
    colorTextButtonPrimaryDefault: INK,
    colorTextButtonPrimaryHover: INK,
    colorTextButtonPrimaryActive: INK,
  },
};

const banner = "/* Generated by scripts/generate-theme.mjs. Do not edit. */\n";
writeFileSync(
  new URL("../app/theme.generated.css", import.meta.url),
  banner + generateThemeStylesheet({ theme }) + "\n",
);
